"""rounds.py — the round record, `.nopekit/round.json` (SPEC decision 18).

The resolution at the end of a round, as tokens: every claim's and
requirement's status key, the counts, the readiness token, each evaluator's
outcome and the entry it stands on, and the typed graph (`graph.py`) — with the
digests of the records, the verdict cache and the design it was computed from,
a round number, and a digest of itself. Tracked, so a pull request that flips
C1 from checked to failing shows as one line, and a history walk reads a past
round with `git show` without judging it again under a newer nopekit.

**An output, never a source.** Written ONLY by `nopekit round` (and, from phase
4, by the merge command), never by `check`; nothing in the spine reads it as input —
only `cli` imports this module, and only to say what changed since the last
round and whether the record is current (`state`). A reader that finds its
self-digest broken says "edited by hand"; one that finds the records, the
verdict cache or the design moved since says "behind the records". Invariant 8
holds it (`test_round.OnlyRoundWritesTheRoundRecord`,
`test_round.NothingReadsTheRoundRecordForTruth`). What slipped through in the
design this replaced: a tracked summary that `check` rewrote would have made
every check a tracked write, and a summary a reader trusted would have been a
second producer of every status (S-41: the committed readiness report had
drifted from its ledger).

**Byte-stable.** No clock, no git revision, no absolute path, no spine digest,
and no words but the fixed `HEADER`: keys in a fixed order, JSON indent 2,
UTF-8 as itself, one newline. The same records, cache and design give the same
bytes on every machine where the resolution is the same (a missing tool, a
remembered crash in the ignored cache and an input's basis searched over the
user's packs are where it is not — SPINE_CONTRACT's limits).
"""
from __future__ import annotations

import hashlib
import json
import os
from typing import Any, Mapping, NamedTuple

from . import store
from .util import NopekitError, atomic_write_text, seal

#: Where the round record lives, relative to the project root.
ROUND_REL = ".nopekit/round.json"
ROUND_NAME = "round.json"

#: The record's schema. A record with a greater one was written by a newer
#: nopekit: read as `newer`, and never rewritten (a downgrade would drop what
#: this one cannot see) — but only when its self-digest holds. The seal rule
#: (`self` is the seal of every other key, `self_digest`) is part of the format
#: at every schema: a nopekit that changes it changes the file's name, never
#: only its schema. What slipped through (review of phase 3a): `newer` was
#: decided before the seal, so a hand edit that bumped `schema` beside a forged
#: `"C1": "checked"` read "written by a newer nopekit", never "edited by hand",
#: and `round` never replaced it.
SCHEMA = 1

#: The one sentence the record holds. Fixed: a vocabulary edit must never move a
#: tracked byte (the record holds tokens, never words).
HEADER = ("generated by `nopekit round`: the resolution at the end of a round, as tokens, "
          "with the digests of what it was computed from. An output: nothing reads it for "
          "truth. Do not edit it; `nopekit round` writes it again.")

#: What the record is computed from, in the order a reader names what moved.
MOVED = ("records", "verdicts", "design")

#: What `state` names when none of `MOVED` moved and the record still differs
#: from what `round` would write now: the resolution moved through something
#: the three digests do not cover — an evaluator's code, its controls, a pack,
#: a tool. What slipped through (review of phase 3a): after a gate-code edit
#: `status` listed three claims Stale beside "round record: round 1, current".
#: *Rejected:* digesting each evaluator's code and controls into
#: `computed_from` (a second copy of the cache's own keying, and still blind to
#: a pack installed or a tool gone).
RESOLUTION = "resolution"

#: The keys every record holds, in file order. `generated`, `schema`, `round`
#: and `self` are the record's own; the rest are what it records — two records
#: equal on those say the same thing, whatever their round.
KEYS = ("generated", "schema", "round", "computed_from", "readiness", "milestones",
        "counts", "claims", "requirements", "disagree", "evaluators", "graph", "self")
_OWN = frozenset({"generated", "schema", "round", "self"})


class Previous(NamedTuple):
    """The round record on disk: ``state`` — ``absent``, ``ok``, ``edited``
    (its self-digest does not match), ``unreadable`` (not strict JSON, or not
    an object: a merge conflict lands here) or ``newer`` (a greater schema);
    ``doc`` the parsed object (None when absent or unreadable); ``round`` its
    number when it is an int >= 1; ``schema``; ``why`` one line for
    ``unreadable``."""

    state: str
    doc: dict | None
    round: int | None
    schema: int | None
    why: str


class RoundState(NamedTuple):
    """Whether the round record says what the project holds now: ``state`` —
    ``absent``, ``current``, ``behind``, ``edited``, ``unreadable`` or
    ``newer``; ``moved`` — the `MOVED` members that differ, or ``(RESOLUTION,)``
    when none did and what it records still differs (``behind``)."""

    state: str
    round: int | None
    moved: tuple
    schema: int | None
    why: str


class Flip(NamedTuple):
    """One token that moved: ``before`` None when it appeared, ``after`` None
    when it went."""

    id: str
    before: str | None
    after: str | None


class Changes(NamedTuple):
    """What changed since the previous round record. ``compared`` only when
    that record read ``ok``; ``replaced`` says why not (``edited``,
    ``unreadable``, ``absent``; ``""`` when compared). ``instructions`` are the
    instruction files whose digest moved, compared only when both records hold
    the model's code; ``unrecorded`` — the last record held it and this one
    does not (the model does not load)."""

    compared: bool
    replaced: str
    claims: tuple
    requirements: tuple
    verdicts: tuple
    instructions: tuple
    readiness: tuple | None
    moved: tuple
    unrecorded: bool = False


class Written(NamedTuple):
    """What `write` did: ``written`` (bytes changed on disk), the ``round`` the
    record holds now, the ``previous`` record, what ``changes`` since it, and
    ``refused`` (``newer``, or ``""``)."""

    written: bool
    round: int | None
    previous: Previous
    changes: Changes
    refused: str


def path_of(root: str) -> str:
    return os.path.join(store.nopekit_dir(root), ROUND_NAME)


def verdicts_digest(root: str) -> str:
    """sha256 over every file under `.nopekit/verdicts/` — its posix path and
    the sha256 of its bytes, in `store._walk_files`' sorted order, dot entries
    (an atomic write's temp) skipped. It moves when an entry is filed or
    removed, and never with the clock."""
    base = os.path.join(store.nopekit_dir(root), store.VERDICTS_NAME)
    rel = f"{store.NOPEKIT_DIR}/{store.VERDICTS_NAME}"
    digest = hashlib.sha256(b"nopekit-verdicts-v1\x00")
    for name in store._walk_files(base, rel):
        full = os.path.join(root, *name.split("/"))
        try:
            with open(full, "rb") as fh:
                data = fh.read()
        except OSError:
            continue
        digest.update(name.encode("utf-8") + b"\x00"
                      + hashlib.sha256(data).hexdigest().encode("ascii") + b"\n")
    return digest.hexdigest()


def computed_from(root: str, design: Mapping[str, Any] | None) -> dict:
    """``{"records", "verdicts", "design"}``: `store.records_digest`,
    `verdicts_digest`, and the seal of `verdicts.design_of` — the current
    article's ``built_from``, so a model or data-file edit that files no new
    verdict still reads as moved (``""`` when the model does not load). No
    spine or version digest: a nopekit upgrade is not "behind the records"."""
    return {"records": store.records_digest(root), "verdicts": verdicts_digest(root),
            "design": seal(design) if design else ""}


def body(computed: Mapping[str, str], tokens: Any, graph: Any) -> dict:
    """The record's content, without its round number or self-digest."""
    return {
        "generated": HEADER,
        "schema": SCHEMA,
        "round": None,
        "computed_from": {key: str(computed.get(key, "") or "") for key in MOVED},
        "readiness": tokens.readiness,
        "milestones": dict(tokens.milestones),
        "counts": dict(tokens.counts),
        "claims": dict(tokens.claims),
        "requirements": dict(tokens.requirements),
        "disagree": {"claims": list(tokens.disagree.get("claims", ())),
                     "requirements": list(tokens.disagree.get("requirements", ()))},
        "evaluators": {gid: dict(row) for gid, row in tokens.evaluators.items()},
        "graph": graph.to_dict() if hasattr(graph, "to_dict") else dict(graph),
    }


def self_digest(doc: Mapping[str, Any]) -> str:
    """The seal of ``doc`` without its ``self``."""
    return seal({k: v for k, v in doc.items() if k != "self"})


def sealed(content: Mapping[str, Any], round_: int) -> dict:
    """``content`` as the record holds it at round ``round_``: its keys in
    `KEYS` order, the round set, and its self-digest."""
    doc = {key: content[key] for key in KEYS if key in content and key != "self"}
    doc["round"] = round_
    doc["self"] = self_digest(doc)
    return {key: doc[key] for key in KEYS}


def render(doc: Mapping[str, Any]) -> bytes:
    """The record's bytes: indent 2, UTF-8 as itself, NaN refused, one newline."""
    return (json.dumps(doc, indent=2, ensure_ascii=False, allow_nan=False)
            + "\n").encode("utf-8")


def _strict(pairs: list) -> dict:
    out: dict = {}
    for key, value in pairs:
        if key in out:
            raise ValueError(f"duplicate key {key!r}")
        out[key] = value
    return out


def _no_constant(name: str) -> Any:
    raise ValueError(f"{name} is not JSON")


def read(root: str) -> Previous:
    """The round record on disk, as `Previous`. Never raises on its content."""
    path = path_of(root)
    try:
        with open(path, "rb") as fh:
            raw = fh.read()
    except FileNotFoundError:
        return Previous("absent", None, None, None, "")
    except OSError as exc:
        return Previous("unreadable", None, None, None, " ".join(str(exc).split()))
    try:
        doc = json.loads(raw.decode("utf-8"), object_pairs_hook=_strict,
                         parse_constant=_no_constant)
    except (UnicodeDecodeError, ValueError) as exc:
        return Previous("unreadable", None, None, None,
                        " ".join(str(exc).splitlines()[0].split()) if str(exc) else "not JSON")
    if not isinstance(doc, dict):
        return Previous("unreadable", None, None, None,
                        f"expected a JSON object, found {type(doc).__name__}")
    schema = doc.get("schema")
    schema = schema if isinstance(schema, int) and not isinstance(schema, bool) else None
    number = doc.get("round")
    number = number if isinstance(number, int) and not isinstance(number, bool) \
        and number >= 1 else None
    if not isinstance(doc.get("self"), str) or self_digest(doc) != doc["self"]:
        return Previous("edited", doc, number, schema, "")
    if schema is not None and schema > SCHEMA:
        return Previous("newer", doc, number, schema, "")
    return Previous("ok", doc, number, schema, "")


def state(root: str, computed_now: Mapping[str, str],
          content: Mapping[str, Any] | None = None) -> RoundState:
    """Whether the round record on disk is current with ``computed_now``
    (`computed_from` of the project as it is) and, given ``content`` (`body`'s,
    what `round` would write now), says what it would say: a record whose
    three digests all hold but whose tokens or graph differ is behind, naming
    `RESOLUTION`."""
    prev = read(root)
    if prev.state != "ok":
        return RoundState(prev.state, prev.round, (), prev.schema, prev.why)
    held = prev.doc.get("computed_from") if isinstance(prev.doc, dict) else None
    held = held if isinstance(held, dict) else {}
    moved = tuple(key for key in MOVED if held.get(key) != computed_now.get(key))
    if not moved and content is not None and not _same(prev.doc, content):
        moved = (RESOLUTION,)
    return RoundState("behind" if moved else "current", prev.round, moved, prev.schema, "")


def _flips(before: Mapping[str, Any], after: Mapping[str, Any]) -> tuple:
    ids = sorted(set(before) | set(after), key=store._natural)
    return tuple(Flip(i, before.get(i), after.get(i)) for i in ids
                 if before.get(i) != after.get(i))


def _dict(doc: Mapping[str, Any] | None, key: str) -> dict:
    value = doc.get(key) if isinstance(doc, Mapping) else None
    return value if isinstance(value, dict) else {}


def changes(previous: Previous, content: Mapping[str, Any],
            computed_now: Mapping[str, str]) -> Changes:
    """What moved between ``previous`` and ``content`` (`body`'s)."""
    if previous.state != "ok":
        replaced = previous.state if previous.state in ("edited", "unreadable") else "absent"
        return Changes(False, replaced, (), (), (), (), None, ())
    doc = previous.doc or {}
    claim_flips = _flips(_dict(doc, "claims"), content.get("claims") or {})
    requirement_flips = _flips(_dict(doc, "requirements"), content.get("requirements") or {})
    before_eval = _dict(doc, "evaluators")
    new_verdicts = []
    for gid, row in sorted((content.get("evaluators") or {}).items(),
                           key=lambda kv: store._natural(kv[0])):
        entry = row.get("entry") if isinstance(row, Mapping) else None
        was = before_eval.get(gid)
        was_entry = was.get("entry") if isinstance(was, Mapping) else None
        if entry is not None and entry != was_entry:
            new_verdicts.append(gid)
    before_nodes = _dict(_dict(doc, "graph"), "nodes")
    after_nodes = (content.get("graph") or {}).get("nodes") or {}

    def instructions(nodes: Mapping[str, Any]) -> dict:
        return {nid: (attrs or {}).get("digest") for nid, attrs in nodes.items()
                if nid.startswith("instruction:") and isinstance(attrs, Mapping)}

    # Compared only when both records hold the model's code. What slipped
    # through (review of phase 3a): a model that stopped loading records no
    # instruction node, so every file of the last round read "moved" though
    # none had; `instructions_unrecorded` says that instead.
    before_code, after_code = instructions(before_nodes), instructions(after_nodes)
    moved_code = _flips(before_code, after_code) if before_code and after_code else ()
    unrecorded = bool(before_code) and not after_code
    readiness = None
    if doc.get("readiness") != content.get("readiness"):
        readiness = (doc.get("readiness"), content.get("readiness"))
    held = _dict(doc, "computed_from")
    moved = tuple(key for key in MOVED if held.get(key) != computed_now.get(key))
    return Changes(True, "", claim_flips, requirement_flips, tuple(new_verdicts),
                   tuple(f.id for f in moved_code), readiness, moved, unrecorded)


def _same(doc: Mapping[str, Any] | None, content: Mapping[str, Any]) -> bool:
    if not isinstance(doc, Mapping):
        return False
    keys = (set(doc) | set(content)) - _OWN
    return all(doc.get(key) == content.get(key) for key in keys)


def write(root: str, content: Mapping[str, Any]) -> Written:
    """Write the round record for ``content`` (`body`'s), and only when it moved:
    nothing over a newer schema; nothing when the record on disk reads ``ok``
    and says the same on every key but its own; otherwise round = the previous
    round + 1 (an edited record's included), else 1, and the bytes are written
    only where they differ."""
    previous = read(root)
    found = changes(previous, content, content.get("computed_from") or {})
    if previous.state == "newer":
        return Written(False, previous.round, previous, found, "newer")
    if previous.state == "ok" and previous.round is not None and _same(previous.doc, content):
        return Written(False, previous.round, previous, found, "")
    number = previous.round + 1 if previous.round is not None else 1
    data = render(sealed(content, number))
    path = path_of(root)
    try:
        with open(path, "rb") as fh:
            if fh.read() == data:
                return Written(False, number, previous, found, "")
    except OSError:
        pass
    try:
        atomic_write_text(path, data.decode("utf-8"))
    except OSError as exc:
        raise NopekitError(f"{ROUND_REL} could not be written: {exc}") from None
    return Written(True, number, previous, found, "")


