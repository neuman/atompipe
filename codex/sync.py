"""Write the Codex copies of the plugin's skills from the Claude Code ones.

``skills/<name>/SKILL.md`` is the source and Claude Code reads it unchanged;
``codex/skills/<name>/SKILL.md`` is an output, written by this script and never
edited by hand. ``tests/test_codex.py`` goes red when a copy differs from what
this script would write now, and names the command::

    python3 codex/sync.py

Why a copy and not the same files: Claude Code substitutes
``${CLAUDE_PLUGIN_ROOT}`` in a plugin skill's body, and Codex is documented to
set that variable for plugin hooks only, not to substitute it in a skill. So
the copy names the plugin's root as ``<plugin-root>`` and its preamble says how
to resolve it from the skill's own path, which Codex shows the agent.
*Rejected:* rewriting ``skills/`` in agent-neutral terms for both hosts (the
Claude Code skill would get weaker to serve the other host, and Claude Code is
what this plugin was built and tested in); a ``$NOPEKIT_ROOT`` exported once
(each command starts a fresh shell, the mistake ``tests/test_plugin.py``'s
``SESSION_STATE`` already catches); a hand-kept second skill (two texts drift,
and nobody notices).

Standard library only, like the spine, and nothing here is imported by it.
"""
from __future__ import annotations

import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(REPO, "skills")
TARGET = os.path.join(REPO, "codex", "skills")

#: How the copy names the plugin's root in place of ``${CLAUDE_PLUGIN_ROOT}``.
ROOT = "<plugin-root>"

#: Each (Claude Code's word, the copy's), applied in order. Kept short on
#: purpose: every row is a place the two skills say different things.
#: *Rejected:* rewording the skill's advice for Codex here (that is a second
#: skill under a script's name).
REPLACEMENTS: tuple[tuple[str, str], ...] = (
    ("${CLAUDE_PLUGIN_ROOT}", ROOT),
    ("each Bash call", "each shell command"),
)

PREAMBLE = """\
> **The Codex copy.** Generated by `codex/sync.py` from `skills/{name}/SKILL.md`;
> never edit it by hand. Below, `{root}` stands for the absolute path of the plugin's
> root: the directory that holds `.codex-plugin/plugin.json`, three levels above the
> directory holding this file. Write that path in its place in every command and every
> file you are told to read; each shell command starts in a fresh shell, so nothing
> set in one reaches the next.
>
> The plugin's Stop hook (`hooks/hooks.json`) runs only where this Codex install runs
> and trusts plugin hooks. Where it does not, no round is committed when your turn
> ends: run `nopekit round` yourself at the end of a turn (it writes the round record
> and commits nothing), and tell the person once that their rounds are not being
> committed, and why.
"""


def render(name: str, text: str) -> str:
    """The Codex copy of the skill ``name`` whose text is ``text``: the front
    matter as it stands, the preamble, then the body with ``REPLACEMENTS``."""
    head, body = "", text
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end < 0:
            raise ValueError(f"skills/{name}/SKILL.md: front matter is not closed")
        head, body = text[:end + 5], text[end + 5:]
    for old, new in REPLACEMENTS:
        body = body.replace(old, new)
    return head + "\n" + PREAMBLE.format(name=name, root=ROOT) + body


def expected() -> dict[str, str]:
    """Every copy this script writes, by its path relative to the repository."""
    out: dict[str, str] = {}
    for name in sorted(os.listdir(SOURCE)):
        path = os.path.join(SOURCE, name, "SKILL.md")
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8", newline="") as fh:
            out[f"codex/skills/{name}/SKILL.md"] = render(name, fh.read())
    return out


def main() -> int:
    want = expected()
    for rel, text in want.items():
        path = os.path.join(REPO, *rel.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        try:
            with open(path, encoding="utf-8", newline="") as fh:
                if fh.read() == text:
                    continue
        except FileNotFoundError:
            pass
        with open(path, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
        print(f"wrote {rel}")
    if os.path.isdir(TARGET):
        for name in sorted(os.listdir(TARGET)):
            if f"codex/skills/{name}/SKILL.md" not in want:
                print(f"codex/skills/{name}/ has no source skill; remove it", file=sys.stderr)
                return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
